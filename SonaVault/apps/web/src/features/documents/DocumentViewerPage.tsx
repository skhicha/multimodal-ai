import { useEffect, useState } from "react";
import { motion } from "framer-motion";
import {
  Activity,
  Code,
  FileCode,
  FileText,
  Layers,
  Search,
} from "lucide-react";
import { useSearchParams } from "react-router-dom";
import {
  CartesianGrid,
  Legend,
  Line,
  LineChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from "recharts";

import AppShell from "@/components/ui/AppShell";
import { getDocumentChunks, type DocumentChunkOut } from "@/lib/api";

const DEFAULT_DOC_SHA = "d8f0a1b2c3d4e5f6a7b8c9d0e1f2a3b4c5d6e7f8a9b0c1d2e3f4a5b6c7d8e9f0";

const MOCK_CHUNKS: DocumentChunkOut[] = [
  {
    index: 0,
    page_or_section: 1,
    text: "NOAA SanctSound Project Technical Memorandum: Automated acoustic recording package (ARP) deployment summary for Channel Islands sanctuary station CI01. Calibrated broadband hydrophone sensitivity -172 dB V/µPa.",
  },
  {
    index: 1,
    page_or_section: 1,
    text: "Baseline ambient sound pressure level measurements over the 10Hz-20kHz band averaged 98.4 dB re 1µPa with dominant low-frequency energy generated by commercial shipping traffic traversing the Santa Barbara Channel.",
  },
  {
    index: 2,
    page_or_section: 2,
    text: "Bioacoustic detections: Seasonal presence of Blue Whales (Balaenoptera musculus) detected via characteristic D-calls and B-calls between July and November. Mean call duration 14.8 seconds with peak spectral density at 45Hz.",
  },
  {
    index: 3,
    page_or_section: 3,
    text: "Anthropogenic sound metrics: 42 vessel passage events recorded exceeding 120 dB re 1µPa threshold. Maximum recorded transient reached 138.2 dB coinciding with panamax container vessel passing within 1.2 nautical miles.",
  },
];

const MOCK_SPL_OCTAVE_DATA = [
  { freq: "63 Hz", baseline: 92, vessel_active: 118, bio_active: 95 },
  { freq: "125 Hz", baseline: 88, vessel_active: 114, bio_active: 92 },
  { freq: "250 Hz", baseline: 84, vessel_active: 106, bio_active: 88 },
  { freq: "500 Hz", baseline: 81, vessel_active: 99, bio_active: 84 },
  { freq: "1 kHz", baseline: 78, vessel_active: 92, bio_active: 82 },
  { freq: "2 kHz", baseline: 75, vessel_active: 85, bio_active: 81 },
  { freq: "4 kHz", baseline: 72, vessel_active: 79, bio_active: 78 },
  { freq: "8 kHz", baseline: 69, vessel_active: 74, bio_active: 76 },
];

export default function DocumentViewerPage() {
  const [searchParams] = useSearchParams();
  const sha256Param = searchParams.get("sha256") || DEFAULT_DOC_SHA;

  const [chunks, setChunks] = useState<DocumentChunkOut[]>(MOCK_CHUNKS);
  const [selectedChunk, setSelectedChunk] = useState<DocumentChunkOut>(MOCK_CHUNKS[0]);
  const [searchTerm, setSearchTerm] = useState("");

  useEffect(() => {
    getDocumentChunks(sha256Param)
      .then((res) => {
        if (res.chunks && res.chunks.length > 0) {
          setChunks(res.chunks);
          setSelectedChunk(res.chunks[0]);
        }
      })
      .catch(() => {});
  }, [sha256Param]);

  const filteredChunks = chunks.filter((c) =>
    searchTerm ? c.text.toLowerCase().includes(searchTerm.toLowerCase()) : true
  );

  return (
    <AppShell>
      <motion.div
        initial={{ opacity: 0, y: 10 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.3 }}
        className="space-y-6"
      >
        <div>
          <div className="flex items-center gap-2">
            <span className="flex h-8 w-8 items-center justify-center rounded-lg bg-tide-500/20 text-tide-300 border border-tide-400/30">
              <FileCode size={18} />
            </span>
            <h1 className="text-2xl font-bold tracking-tight text-white font-display">
              Sanctuary Telemetry &amp; Documents
            </h1>
          </div>
          <p className="mt-1 font-mono text-xs text-slate-400 truncate max-w-2xl">
            DOCUMENT SHA-256: {sha256Param}
          </p>
        </div>

        {/* 1/3-Octave SPL Multi-Band Spectrum Chart */}
        <div className="rounded-xl border border-white/10 bg-abyss-900/80 p-5 space-y-4">
          <div className="flex flex-wrap items-center justify-between gap-2 border-b border-white/10 pb-3">
            <div>
              <h2 className="text-sm font-semibold text-white flex items-center gap-2">
                <Activity size={16} className="text-tide-400" />
                Acoustic Frequency Octave Sound Pressure (dB re 1µPa)
              </h2>
              <p className="text-xs text-slate-400">
                Calibrated 1/3-octave band sound levels extracted from NOAA sanctuary XML telemetry.
              </p>
            </div>
            <span className="rounded bg-tide-500/10 px-2.5 py-1 text-xs font-mono text-tide-300 border border-tide-400/20">
              Station CI01 ARP Deployment
            </span>
          </div>

          <div className="h-64 w-full">
            <ResponsiveContainer width="100%" height="100%">
              <LineChart data={MOCK_SPL_OCTAVE_DATA}>
                <CartesianGrid strokeDasharray="3 3" stroke="#1f293d" />
                <XAxis dataKey="freq" stroke="#64748b" fontSize={11} />
                <YAxis domain={[60, 130]} stroke="#64748b" fontSize={11} unit="dB" />
                <Tooltip
                  contentStyle={{
                    backgroundColor: "#0a1120",
                    borderColor: "rgba(255,255,255,0.1)",
                    borderRadius: "8px",
                    fontSize: "12px",
                  }}
                />
                <Legend wrapperStyle={{ fontSize: "12px", paddingTop: "10px" }} />
                <Line
                  type="monotone"
                  dataKey="vessel_active"
                  name="Vessel Transit Peak"
                  stroke="#fb7185"
                  strokeWidth={2}
                  dot={{ r: 3 }}
                />
                <Line
                  type="monotone"
                  dataKey="bio_active"
                  name="Biophony Event"
                  stroke="#2dd4bf"
                  strokeWidth={2}
                  dot={{ r: 3 }}
                />
                <Line
                  type="monotone"
                  dataKey="baseline"
                  name="Ambient Baseline"
                  stroke="#94a3b8"
                  strokeDasharray="4 4"
                  strokeWidth={1.5}
                />
              </LineChart>
            </ResponsiveContainer>
          </div>
        </div>

        {/* Chunks Explorer Split View */}
        <div className="grid grid-cols-1 gap-6 lg:grid-cols-3">
          {/* Chunks List */}
          <div className="space-y-3">
            <div className="rounded-xl border border-white/10 bg-abyss-900/80 p-4 space-y-3">
              <div className="flex items-center gap-2 border-b border-white/10 pb-2">
                <Search size={14} className="text-slate-400" />
                <input
                  type="text"
                  placeholder="Filter extracted chunks..."
                  value={searchTerm}
                  onChange={(e) => setSearchTerm(e.target.value)}
                  className="w-full bg-transparent text-xs text-white placeholder-slate-500 outline-none"
                />
              </div>

              <div className="space-y-2 max-h-[460px] overflow-y-auto pr-1">
                {filteredChunks.map((chunk) => (
                  <button
                    key={chunk.index}
                    onClick={() => setSelectedChunk(chunk)}
                    className={`w-full text-left rounded-lg p-3 transition border ${
                      selectedChunk.index === chunk.index
                        ? "bg-tide-500/15 border-tide-400/50 text-white"
                        : "bg-abyss-950/40 border-white/5 text-slate-300 hover:bg-white/5"
                    }`}
                  >
                    <div className="flex items-center justify-between font-mono text-[11px] mb-1">
                      <span className="font-bold text-tide-300">Chunk #{chunk.index}</span>
                      <span className="text-slate-500">Page {chunk.page_or_section || 1}</span>
                    </div>
                    <p className="text-xs line-clamp-2">{chunk.text}</p>
                  </button>
                ))}
              </div>
            </div>
          </div>

          {/* Chunk Deep Details & Vectorization Status */}
          <div className="lg:col-span-2 space-y-4">
            <div className="rounded-xl border border-white/10 bg-abyss-900/80 p-6 space-y-5">
              <div className="flex items-center justify-between border-b border-white/10 pb-3">
                <div className="flex items-center gap-2">
                  <FileText size={16} className="text-tide-400" />
                  <h3 className="text-sm font-semibold text-white">
                    Chunk #{selectedChunk.index} Text &amp; Token Breakdown
                  </h3>
                </div>
                <span className="rounded bg-emerald-500/10 px-2 py-0.5 text-xs font-mono text-emerald-400 border border-emerald-500/20">
                  Indexed in Qdrant
                </span>
              </div>

              <div className="rounded-lg bg-abyss-950 p-4 border border-white/10 text-xs text-slate-200 leading-relaxed font-sans">
                {selectedChunk.text}
              </div>

              {/* Embedding Representation Metadata */}
              <div className="grid grid-cols-2 gap-3 text-xs">
                <div className="rounded-lg bg-abyss-950/60 p-3.5 border border-white/5 space-y-1">
                  <div className="flex items-center gap-1.5 text-tide-400 font-mono text-[11px] font-bold">
                    <Layers size={13} /> BGE-M3 Dense Embedding
                  </div>
                  <p className="font-mono text-slate-300">1024-dimensional float32 vector</p>
                  <p className="text-[11px] text-slate-500">Cosine metric • HNSW indexed</p>
                </div>

                <div className="rounded-lg bg-abyss-950/60 p-3.5 border border-white/5 space-y-1">
                  <div className="flex items-center gap-1.5 text-signal-amber font-mono text-[11px] font-bold">
                    <Code size={13} /> BGE-M3 Sparse Lexical Tokens
                  </div>
                  <p className="font-mono text-slate-300">Learned token weight indices</p>
                  <p className="text-[11px] text-slate-500">BM25 / Inverted index in Qdrant</p>
                </div>
              </div>
            </div>
          </div>
        </div>
      </motion.div>
    </AppShell>
  );
}
